def h2h_section():
    """Amendment 2 (head-to-head): numbers come only from data/h2h_experiment.json and site/data/h2h/*.json."""
    import glob
    jp = f"{D}/h2h_experiment.json"
    if not os.path.exists(jp):
        return ""
    X = json.load(open(jp))
    if "dev" not in X:
        return ""
    sp = X["spec"]
    out = ["", "## Head-to-head (Amendment 2)", "",
           "Question (Mo): does the last-10-meetings record between the two clubs improve the forecast? Pre-registered in `BACKTEST_SPEC.md` (Amendment 2) before any metric with the feature was computed; code `model/h2h_experiment.py`, results `data/h2h_experiment.json`.", "",
           f"**Feature.** For each match, the last up to {sp['n_max']} meetings strictly before the weekly cut-off (leagues, second tiers, European cups, domestic cups; no friendlies). For each, actual goal difference minus the goal difference that week's own Dixon-Coles fit expects, weighted by recency (half-life {sp['half_life_years']} years), shrunk toward zero with {sp['shrink']:.0f} pseudo-meetings: `R`. Expected goals are then multiplied by `exp(+w R)` (home) and `exp(-w R)` (away). `w` in {{{', '.join(str(w) for w in sp['weights'])}}}; `w = 0` reproduces the shipped model exactly (checked against the tuning grid). **Acceptance rule (set in advance):** accept only if 2024-25 RPS improves by at least {sp['threshold_rps']} over `w = 0` with log-loss not higher; the 2025-26 holdout is run once, and only if accepted.", "",
           "### Dev set 2024-25 (the only data used to decide)", "",
           "| Pool | n | w | RPS | change vs w=0 | Log-loss |", "|---|---|---|---|---|---|"]
    for pool, nm in [("eu", "European pool"), ("spl", "Saudi league")]:
        d = X["dev"][pool]; b0 = d["by_weight"]["0.0"]["rps"]
        for w in sp["weights"]:
            r = d["by_weight"][str(float(w))] if str(float(w)) in d["by_weight"] else d["by_weight"][str(w)]
            out.append(f"| {nm} | {d['n']} | {w} | {r['rps']:.5f} | {r['rps'] - b0:+.5f} | {r['ll']:.5f} |")
    out += ["", "| Pool | Decision | Reason |", "|---|---|---|"]
    for pool, nm in [("eu", "European pool"), ("spl", "Saudi league")]:
        d = X["dev"][pool]["decision"]
        out.append(f"| {nm} | {'ACCEPTED, w = ' + str(d['w']) if d['accepted'] else 'Not accepted: live model unchanged'} | {d['reason']} |")
    out += ["", "### Diagnostics (not used for any decision)", "",
            "| Pool | Matches with >=1 / >=5 / 10 prior meetings | Mean abs R (goals) | Slope of actual goal-diff residual on R [95% CI] | Implied w [95% CI] |", "|---|---|---|---|---|"]
    for pool, nm in [("eu", "European pool"), ("spl", "Saudi league")]:
        g = X["dev"][pool]["diagnostics"]
        out.append(f"| {nm} | {pc(g['share_ge1'], 0)} / {pc(g['share_ge5'], 0)} / {pc(g['share_10'], 0)} | {g['mean_abs_R']:.3f} | {g['slope_gd_per_R']:.3f} [{g['slope_ci95'][0]:.3f}, {g['slope_ci95'][1]:.3f}] | {g['implied_w']:.3f} [{g['implied_w_ci95'][0]:.3f}, {g['implied_w_ci95'][1]:.3f}] |")
    ho = X.get("holdout", {})
    out += ["", "### Holdout 2025-26", ""]
    for pool, nm in [("eu", "European pool"), ("spl", "Saudi league")]:
        if pool in ho:
            h = ho[pool]
            out.append(f"* {nm} (w = {h['w_h2h']}, n = {h['n']}): RPS {h['rps_w']:.5f} vs {h['rps_w0']:.5f} at w = 0; difference {ci(h['rps_diff_boot'])}; log-loss difference {ci(h['ll_diff_boot'])}.")
        else:
            out.append(f"* {nm}: not run (not accepted on the dev set; the pre-registration allows one holdout run only for an accepted pool).")
    files = [json.load(open(x)) for x in sorted(glob.glob(f"{ROOT}/site/data/h2h/*.json"))]
    if files:
        full = sum(1 for x in files if x["summary"]["n"] >= 10)
        out += ["", "### Head-to-head files on the site", "",
                f"{len(files)} files in `site/data/h2h/`, {full} with the full 10 meetings; the rest say how many were found and why (Saudi history from ESPN starts in August 2022; newly promoted clubs have no top-flight history).",
                "The numbers on the match pages are a display of the record; they do not enter the probabilities unless an amendment is accepted."]
    return "\n".join(out) + "\n"


md = md.rstrip("\n") + "\n" + h2h_section()
open(os.path.join(ROOT, "BACKTEST.md"), "w").write(md)
