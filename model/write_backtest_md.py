def f(x, n=4):
    return f"{x:.{n}f}"


def pc(x, n=1):
    return f"{100 * x:.{n}f}%"


def ci(t):
    return f"{t[0]:+.4f} [{t[1]:+.4f}, {t[2]:+.4f}]"


def model_table(block):
    rows = ["| Model | RPS | Log-loss | Brier | W/D/L accuracy | Headline-score hit | Top-score hit | Avg. prob. of actual score |", "|---|---|---|---|---|---|---|---|"]
    names = {"shipped": "**Shipped model**", "dc_only": "Dixon-Coles only (w=1)", "elo_only": "Elo only", "base_rates": "Base rates", "uniform": "Uniform 1/3"}
    for k in ["shipped", "dc_only", "elo_only", "base_rates", "uniform"]:
        m = block["models"][k]
        has = "head_hit" in m
        rows.append(f"| {names[k]} | {f(m['rps'])} | {f(m['ll'])} | {f(m['brier'])} | {pc(m['acc'])} | {pc(m['head_hit']) if has else '-'} | {pc(m['top_hit']) if has else '-'} | {pc(m['p_actual_score'], 2) if has else '-'} |")
    rows.append(f"| Home win always | - | - | - | {pc(block['home_win_always_acc'])} | - | - | - |")
    return "\n".join(rows)


def boot_table(block):
    rows = ["| Shipped minus ... | RPS difference [95% CI] | Log-loss difference [95% CI] |", "|---|---|---|"]
    for k, nm in [("base_rates", "base rates"), ("uniform", "uniform"), ("elo_only", "Elo only"), ("dc_only", "Dixon-Coles only")]:
        b = block["bootstrap"][f"shipped_minus_{k}"]
        rows.append(f"| {nm} | {ci(b['rps'])} | {ci(b['ll'])} |")
    return "\n".join(rows) + "\n\nNegative = the shipped model is better. An interval that contains 0 means the two are not distinguishable on this sample."


def tune_table(js, n=8, key="rps_all"):
    T = pd.DataFrame(js["tuning_grid"]).sort_values(key).head(n)
    if js["pool"] == "spl":
        rows = ["| xi | ridge | w (Dixon-Coles weight) | RPS | Log-loss |", "|---|---|---|---|---|"]
        for r in T.itertuples():
            rows.append(f"| {r.xi} | {r.reg:g} | {r.w:g} | {f(r.rps_all)} | {f(r.ll_all)} |")
        return "\n".join(rows)
    rows = ["| xi | ridge | w (Dixon-Coles weight) | RPS domestic | RPS Champions League | RPS all | Log-loss all |", "|---|---|---|---|---|---|---|"]
    for r in T.itertuples():
        ucl = "-" if pd.isna(r.rps_ucl) else f(r.rps_ucl)
        rows.append(f"| {r.xi} | {r.reg:g} | {r.w:g} | {f(r.rps_dom)} | {ucl} | {f(r.rps_all)} | {f(r.ll_all)} |")
    return "\n".join(rows)


def per_comp(csvname):
    m = pd.read_csv(f"{D}/{csvname}")
    rows = ["| Competition | Matches | W/D/L accuracy | Headline-score hit | RPS | Log-loss |", "|---|---|---|---|---|---|"]
    y = np.where(m.hg > m.ag, 0, np.where(m.hg == m.ag, 1, 2))
    p = m[["ph", "pd", "pa"]].values
    m["acc"] = (p.argmax(1) == y).astype(float)
    names = {"epl": "Premier League", "laliga": "La Liga", "ligue1": "Ligue 1", "bundesliga": "Bundesliga", "seriea": "Serie A", "ucl": "Champions League", "spl": "Saudi Pro League"}
    for c in ["epl", "laliga", "ligue1", "bundesliga", "seriea", "ucl", "spl"]:
        s = m[m.comp == c]
        if len(s):
            rows.append(f"| {names[c]} | {len(s)} | {pc(s.acc.mean())} | {pc(s.head_hit.mean())} | {f(s.rps.mean())} | {f(s.ll.mean())} |")
    return "\n".join(rows), m, y


def calibration(m, y):
    p = np.concatenate([m.ph.values, m.pd.values, m.pa.values])
    o = np.concatenate([(y == 0), (y == 1), (y == 2)]).astype(float)
    bins = [0, 0.15, 0.25, 0.35, 0.45, 0.55, 0.70, 1.0]
    rows = ["| Predicted probability | Outcomes counted | Average predicted | Actually happened |", "|---|---|---|---|"]
    for lo, hi in zip(bins[:-1], bins[1:]):
        s = (p >= lo) & (p < hi) if hi < 1 else (p >= lo)
        if s.sum():
            rows.append(f"| {int(lo * 100)}-{int(hi * 100)}% | {int(s.sum())} | {pc(p[s].mean())} | {pc(o[s].mean())} |")
    return "\n".join(rows)


